CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    sigla VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),
    setor_id BIGINT NOT NULL REFERENCES setor(id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    matricula VARCHAR(255) NOT NULL,
    tipo VARCHAR(255) NOT NULL CHECK (tipo IN ('SOLICITANTE', 'TECNICO')),
    setor_id BIGINT REFERENCES setor(id)
);

CREATE TABLE chamado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao TEXT NOT NULL,
    local VARCHAR(255) NOT NULL,
    prioridade VARCHAR(255) NOT NULL CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    status VARCHAR(255) NOT NULL CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO')),
    data_abertura TIMESTAMP(6) NOT NULL,
    data_fechamento TIMESTAMP(6),
    solucao TEXT,
    solicitante_id BIGINT NOT NULL REFERENCES usuario(id),
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    tecnico_id BIGINT REFERENCES usuario(id)
);

CREATE TABLE interacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto TEXT NOT NULL,
    data_hora TIMESTAMP(6) NOT NULL,
    chamado_id BIGINT NOT NULL REFERENCES chamado(id),
    autor_id BIGINT NOT NULL REFERENCES usuario(id)
);
